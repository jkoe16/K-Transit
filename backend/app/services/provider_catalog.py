def get_provider_catalog() -> list[dict[str, Any]]:
    settings = get_settings()
    providers: list[dict[str, Any]] = []
    for item in CATALOG:
        provider = dict(item)
        configured_key = provider.pop("configured_key")
        status_key = provider.pop("status_key", None)
        status_override = provider.pop("status_override", None)
        integrated = provider.pop("integrated")
        if status_key:
            status = get_provider_status(
                status_key,
                configured=bool(getattr(settings, configured_key)),
                integrated=integrated,
            )
        else:
            status = {
                "status": status_override or "waiting",
                "last_success_at": None,
                "last_error": (
                    provider["notes"]
                    if status_override in {"review_required", "endpoint_unknown"}
                    else None
                ),
            }
        provider["status"] = status
        provider["key_configured"] = (
            bool(getattr(settings, configured_key)) if configured_key else None
        )
        providers.append(provider)
    return providers
